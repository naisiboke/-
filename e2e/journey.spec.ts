import { test, expect } from '@playwright/test'
test('records a conflict, preserves draft on back, and tracks an adjustment', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('慢慢说。')).toBeVisible()
  await page.screenshot({ path: 'artifacts/home.png', fullPage: true })
  await page.getByText('开始记录', { exact: true }).click()
  await page.getByText('继续', { exact: true }).click()
  await expect(page.getByText('先写下一件发生的事')).toBeVisible()
  await page.locator('textarea').fill('今天陪妈妈复诊，弟弟临时没能来。')
  await page.getByText('继续', { exact: true }).click()
  await page.getByRole('button', { name: '返回上一步' }).click()
  await expect(page.locator('textarea')).toHaveValue('今天陪妈妈复诊，弟弟临时没能来。')
  await page.screenshot({ path: 'artifacts/journal.png', fullPage: true })
  await page.getByText('继续', { exact: true }).click()
  await page.getByText('疲惫', { exact: true }).click()
  await page.getByText('继续', { exact: true }).click()
  await page.locator('textarea').fill('希望提前确认陪诊安排')
  await page.getByText('继续', { exact: true }).click()
  await page.getByText('任务遗漏', { exact: true }).click()
  await page.getByText('还没明确谁负责', { exact: true }).click()
  await page.getByText('看看这次复盘', { exact: true }).click()
  await expect(page.getByText('一次小调整', { exact: true })).toBeVisible()
  await expect(
    page.getByText('下次复诊前两天，提出一个具体的陪诊请求，并约定答复时间。', { exact: true }),
  ).toBeVisible()
  await page.getByText('试过了', { exact: true }).click()
  await page.screenshot({ path: 'artifacts/result.png', fullPage: true })
  await page.getByRole('button', { name: '返回首页' }).click()
  await page.getByRole('button', { name: '回看', exact: true }).click()
  await expect(page.getByText('今天陪妈妈复诊，弟弟临时没能来。', { exact: true })).toBeVisible()
  await page.getByText('调整', { exact: true }).click()
  await expect(page.getByText('试过了', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/history.png', fullPage: true })
  await page.reload()
  await expect(page.getByText('从一次记录开始')).toBeVisible()
  expect(errors).toEqual([])
})
test('AI preview can hide selected names and never sends while unavailable', async ({ page }) => {
  const external: string[] = []
  page.on('request', (r) => {
    if (!r.url().startsWith('http://localhost:5173')) external.push(r.url())
  })
  await page.goto('/')
  await page.getByText('开始记录', { exact: true }).click()
  await page.locator('textarea').fill('张三在和平医院复诊，电话13800138000')
  await page.getByText('继续', { exact: true }).click()
  await page.getByText('继续', { exact: true }).click()
  await page.getByText('继续', { exact: true }).click()
  await page.getByText('任务遗漏', { exact: true }).click()
  await page.getByText('还没明确谁负责', { exact: true }).click()
  await page.getByText('看看这次复盘', { exact: true }).click()
  await page.getByRole('button', { name: 'AI 深化', exact: true }).click()
  await expect(page.locator('textarea')).not.toHaveValue(/13800138000/)
  await page.locator('input').fill('张三,和平医院')
  await page.getByText('隐去', { exact: true }).click()
  await expect(page.locator('textarea')).not.toHaveValue(/张三|和平医院/)
  await page.getByText('取消并清除预览', { exact: true }).click()
  await page.getByText('查看这次复盘与反馈', { exact: false }).click()
  await page.getByLabel('下一次调整内容').locator('textarea').fill('下周一确认陪诊安排')
  await page.getByText('保存调整', { exact: true }).click()
  await expect(page.locator('.action')).toHaveText('下周一确认陪诊安排')
  await page.getByText('导出文本', { exact: true }).click()
  await expect(page.getByText('导出前，再看一眼。')).toBeVisible()
  await expect(page.locator('textarea')).toHaveValue(/张三/)
  expect(external).toEqual([])
})
test('rapid clicks advance exactly one step and editing leaves no new draft', async ({ page }) => {
  await page.goto('/')
  await page.getByText('开始记录', { exact: true }).click()
  await page.locator('textarea').fill('今天复诊没有确认安排')
  await page.getByText('继续', { exact: true }).evaluate((el) => {
    ;(el as HTMLElement).click()
    ;(el as HTMLElement).click()
  })
  await expect(page.getByText('此刻，什么感受？', { exact: true })).toBeVisible()
  await page.getByText('继续', { exact: true }).click()
  await page.getByText('继续', { exact: true }).click()
  await page.getByText('任务遗漏', { exact: true }).click()
  await page.getByText('还没明确谁负责', { exact: true }).click()
  await page.getByText('看看这次复盘', { exact: true }).click()
  await page.getByText('查看这次复盘与反馈', { exact: false }).click()
  await page.getByText('修改记录', { exact: true }).click()
  await page.locator('textarea').fill('修改后的复诊安排')
  for (let i = 0; i < 3; i++) await page.getByText('继续', { exact: true }).click()
  await page.getByText('看看这次复盘', { exact: true }).click()
  await page.getByRole('button', { name: '返回首页' }).click()
  await expect(page.getByText('开始记录', { exact: true })).toBeVisible()
})
